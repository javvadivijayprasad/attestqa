// Flat config (ESLint 9+). Same rule family as pw-emit / bdd2pw.
import js from "@eslint/js";
import tseslint from "typescript-eslint";

export default tseslint.config(
  {
    // `examples/sandbox` is the agent's workspace: its contents are generated
    // by a run, so linting them would fail the package's own lint task on
    // output we did not write.
    // `extension/` is a separate package with its own tsconfig, its own
    // release cycle and its own dependencies. `extension/out` is compiled
    // CommonJS, which this config's ESM rules reject on sight — so linting it
    // here fails the runtime's lint task on generated output belonging to a
    // different package. It brings its own linting when it needs it.
    // `.scratch-bdd2pw/` is where a bdd2pw dry run puts the Page Objects and
    // spec it generates while we measure how many steps bind. It is bdd2pw's
    // output, written by bdd2pw's emitter, and linting it fails this package's
    // lint task on another package's code style — `testInfo` unused in a
    // generated test signature is bdd2pw's call to make, not ours.
    ignores: [
      "dist/**",
      "node_modules/**",
      "examples/**/*.mjs",
      "examples/sandbox/**",
      ".scratch-bdd2pw/**",
      // Generated by bdd2pw when the workspace IS the repo root. Note the
      // singular/plural trap: this package's own tests live in `test/`, and
      // `tests/` + `pages/` at the root are only ever generator output, so
      // ignoring them hides nothing we wrote. (They exist here as leftovers
      // from the run where the adapter passed a hard-coded `--repo .`; the
      // adapter now derives the repo from the feature file's location.)
      "tests/**",
      "pages/**",
      "extension/**",
      // Generated example output and local scratch, not this package's code.
      "examples/sample-project/**",
      "_to_delete/**",
      "*.config.*",
    ],
  },
  js.configs.recommended,
  ...tseslint.configs.recommended,
  {
    files: ["src/**/*.ts", "test/**/*.ts"],
    rules: {
      "@typescript-eslint/no-unused-vars": ["error", { argsIgnorePattern: "^_" }],
      "@typescript-eslint/no-non-null-assertion": "off",
    },
  },
);
