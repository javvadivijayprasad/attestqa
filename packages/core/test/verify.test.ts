describe("the two checks that guard the tool chain", () => {
  // These exist because both were added WITHOUT tests, silently failed to reach
  // disk, and a full agent run passed anyway — the run reused a hand-written
  // spec, filed an unlinked bug, and neither check was there to notice. A
  // verifier check with no test is a check nobody can tell is missing.

  function ws(): string {
    return mkdtempSync(join(tmpdir(), "aqa-v2-"));
  }

  function specIn(dir: string, header: string): void {
    mkdirSync(join(dir, "tests"), { recursive: true });
    writeFileSync(
      join(dir, "tests", "login.spec.ts"),
      `${header}\nimport { test } from "@playwright/test";\n`,
      "utf8",
    );
  }

  /** A ledger in which the run WROTE that spec — which is what the check is about. */
  function readSpec(dir: string): AnyRunEvent[] {
    const led = new Ledger(dir, "run-x");
    led.append("request", { text: "t", skill: "story-to-tests", configHash: "sha256:x" }, 1);
    const call = led.append(
      "call",
      { server: "fs", toolName: "write_file", args: { path: "tests/login.spec.ts" }, startedAt: 2 },
      2,
    );
    led.append(
      "observation",
      { eventIdOfCall: call.eventId, ok: true, result: {}, artefacts: [], durationMs: 1 },
      3,
    );
    return led.read();
  }

  it("raises spec-not-generated-from-feature on a spec the run hand-wrote", async () => {
    const dir = ws();
    specIn(dir, "// Implemented from AB#1 acceptance criteria");
    const v = new StoryToTestsVerifier({ workItem: "1", requireSuiteMembership: false });
    const out = await v.verify({ events: readSpec(dir), workspaceDir: dir });
    expect(out.gaps.map((g) => g.code)).toContain("spec-not-generated-from-feature");
  });

  it("ignores a hand-written spec the run did not touch", async () => {
    // The rule is "the agent must not hand-write a spec", not "every spec here
    // must have come from bdd2pw". A team adopting this with a suite they
    // already own must not fail on every run for something they did before they
    // met the tool.
    const dir = ws();
    specIn(dir, "// written by a human in 2019");
    const led = new Ledger(dir, "run-w");
    led.append("request", { text: "t", skill: "story-to-tests", configHash: "sha256:x" }, 1);
    const v = new StoryToTestsVerifier({ workItem: "1", requireSuiteMembership: false });
    const out = await v.verify({ events: led.read(), workspaceDir: dir });
    expect(out.gaps.map((g) => g.code)).not.toContain("spec-not-generated-from-feature");
  });

  it("accepts a spec carrying bdd2pw's provenance header", async () => {
    // State, not effort: a re-run that finds a correct generated spec passes
    // without regenerating anything.
    const dir = ws();
    specIn(dir, "// Generated by agentic-qa (bdd2pw) from features/login.feature.");
    const v = new StoryToTestsVerifier({ workItem: "1", requireSuiteMembership: false });
    const out = await v.verify({ events: readSpec(dir), workspaceDir: dir });
    expect(out.gaps.map((g) => g.code)).not.toContain("spec-not-generated-from-feature");
  });

  /**
   * A ledger with a successful `bdd2pw.scaffold` and a spec write, in the
   * order given. `scaffoldFirst` is the whole point of the check.
   */
  function scaffoldAndWrite(dir: string, scaffoldFirst: boolean): AnyRunEvent[] {
    const led = new Ledger(dir, `run-${scaffoldFirst ? "ok" : "bad"}`);
    led.append("request", { text: "t", skill: "story-to-tests", configHash: "sha256:x" }, 1);
    let at = 2;
    const emit = (server: string, toolName: string, args: Record<string, unknown>): void => {
      const call = led.append("call", { server, toolName, args, startedAt: at }, at++);
      led.append(
        "observation",
        { eventIdOfCall: call.eventId, ok: true, result: {}, artefacts: [], durationMs: 1 },
        at++,
      );
    };
    const scaffold = (): void =>
      emit("bdd2pw", "scaffold", { feature: "features/login.feature", url: "http://x/" });
    const write = (): void => emit("fs", "write_file", { path: "tests/login.spec.ts" });
    if (scaffoldFirst) {
      scaffold();
      write();
    } else {
      write();
      scaffold();
    }
    return led.read();
  }

  it("accepts a spec written AFTER bdd2pw.scaffold, header or no header", async () => {
    // Real bdd2pw stamps no provenance comment, and step 4 of the skill
    // requires the agent to edit the TODO bodies of what it generated. A check
    // keyed on a marker would call that correct behaviour hand-writing.
    const dir = ws();
    specIn(dir, "// implemented the TODO steps bdd2pw left");
    const v = new StoryToTestsVerifier({ workItem: "1", requireSuiteMembership: false });
    const out = await v.verify({ events: scaffoldAndWrite(dir, true), workspaceDir: dir });
    expect(out.gaps.map((g) => g.code)).not.toContain("spec-not-generated-from-feature");
  });

  it("closes the gap when a scaffold regenerates a hand-written spec", async () => {
    // A gap must describe the PRESENT. The first version of this check asked
    // "did the first scaffold precede the first write" — true or false forever
    // once the run had started, so an agent told about it had no move that
    // could close it. Observed in 20260918T235010Z: the agent hand-edited a
    // spec, was told, scaffolded on the retry, and the gap fired again
    // unchanged; the run ended blocked with a green suite and four test cases
    // created.
    //
    // Scaffolding regenerates the spec from the feature file, which is exactly
    // the state the rule wants. Refusing to accept the remedy teaches the agent
    // that the gap is noise.
    const dir = ws();
    specIn(dir, "// Implemented from AB#1 acceptance criteria");
    const v = new StoryToTestsVerifier({ workItem: "1", requireSuiteMembership: false });
    const out = await v.verify({ events: scaffoldAndWrite(dir, false), workspaceDir: dir });
    expect(out.gaps.map((g) => g.code)).not.toContain("spec-not-generated-from-feature");
  });

  it("still raises it when no scaffold ever ran", async () => {
    // The case the check exists for: across a day of runs the generator was
    // called zero times and `fs.write_file` twenty-five.
    const dir = ws();
    specIn(dir, "// Implemented from AB#1 acceptance criteria");
    const v = new StoryToTestsVerifier({ workItem: "1", requireSuiteMembership: false });
    const out = await v.verify({ events: readSpec(dir), workspaceDir: dir });
    expect(out.gaps.map((g) => g.code)).toContain("spec-not-generated-from-feature");
  });

  it("raises bug-not-linked-to-story when a filed bug has no parentId", async () => {
    // Observed: the first bug this agent proposed carried a title, repro steps
    // and a priority, and nothing tying it to the story it was found against.
    const dir = ws();
    specIn(dir, "// Generated by agentic-qa (bdd2pw) from features/login.feature.");
    const led = new Ledger(dir, "run-y");
    led.append("request", { text: "t", skill: "story-to-tests", configHash: "sha256:x" }, 1);
    const call = led.append(
      "call",
      {
        server: "ado",
        toolName: "wit_work_item_write",
        args: { action: "create", workItemType: "Bug", fields: [] },
        startedAt: 2,
      },
      2,
    );
    led.append(
      "observation",
      { eventIdOfCall: call.eventId, ok: true, result: { id: 99 }, artefacts: [], durationMs: 1 },
      3,
    );
    const v = new StoryToTestsVerifier({ workItem: "1", requireSuiteMembership: false });
    const out = await v.verify({ events: led.read(), workspaceDir: dir });
    expect(out.gaps.map((g) => g.code)).toContain("bug-not-linked-to-story");
  });

  it("accepts a bug linked to the story", async () => {
    const dir = ws();
    const led = new Ledger(dir, "run-z");
    led.append("request", { text: "t", skill: "story-to-tests", configHash: "sha256:x" }, 1);
    const call = led.append(
      "call",
      {
        server: "ado",
        toolName: "wit_work_item_write",
        args: { action: "create", workItemType: "Bug", parentId: 1, fields: [] },
        startedAt: 2,
      },
      2,
    );
    led.append(
      "observation",
      { eventIdOfCall: call.eventId, ok: true, result: { id: 99 }, artefacts: [], durationMs: 1 },
      3,
    );
    const v = new StoryToTestsVerifier({ workItem: "1", requireSuiteMembership: false });
    const out = await v.verify({ events: led.read(), workspaceDir: dir });
    expect(out.gaps.map((g) => g.code)).not.toContain("bug-not-linked-to-story");
  });

  /** A ledger in which the run filed one bug with these arguments. */
  function filedBug(dir: string, args: Record<string, unknown>): AnyRunEvent[] {
    const led = new Ledger(dir, "run-tag");
    led.append("request", { text: "t", skill: "story-to-tests", configHash: "sha256:x" }, 1);
    const call = led.append(
      "call",
      { server: "ado", toolName: "wit_work_item_write", args, startedAt: 2 },
      2,
    );
    led.append(
      "observation",
      { eventIdOfCall: call.eventId, ok: true, result: { id: 99 }, artefacts: [], durationMs: 1 },
      3,
    );
    return led.read();
  }

  it("raises bug-not-marked-as-agent-filed on a bug with no agentic-qa tag", async () => {
    // A bug this runtime files carries the same author as one a human
    // investigated and filed — same PAT, same name. The tag is the only thing
    // that separates them, and step 1a reads open bugs back as context, so an
    // untagged proposal becomes established product knowledge on the next run.
    // (Observed: three agent-filed bugs sat open in the sandbox, one of them
    // for a failure later shown to be an unregistered test account.)
    const dir = ws();
    const v = new StoryToTestsVerifier({ workItem: "1", requireSuiteMembership: false });
    const out = await v.verify({
      events: filedBug(dir, { action: "create", workItemType: "Bug", parentId: 1, fields: [] }),
      workspaceDir: dir,
    });
    expect(out.gaps.map((g) => g.code)).toContain("bug-not-marked-as-agent-filed");
  });

  it("accepts the tag in either spelling the tool takes", async () => {
    const dir = ws();
    const v = new StoryToTestsVerifier({ workItem: "1", requireSuiteMembership: false });
    for (const args of [
      { action: "create", workItemType: "Bug", parentId: 1, tags: "agentic-qa" },
      { action: "create", workItemType: "Bug", parentId: 1, tags: "login; Agentic-QA ; sandbox" },
      {
        action: "create",
        workItemType: "Bug",
        parentId: 1,
        fields: { "System.Tags": "agentic-qa" },
      },
    ]) {
      const out = await v.verify({ events: filedBug(dir, args), workspaceDir: dir });
      expect(out.gaps.map((g) => g.code)).not.toContain("bug-not-marked-as-agent-filed");
    }
  });

  it("matches the whole tag, not a prefix", () => {
    // A later run looking for its own output must not sweep up a tag a human
    // named similarly.
    expect(hasAgentTag("agentic-qa")).toBe(true);
    expect(hasAgentTag(" AGENTIC-QA ")).toBe(true);
    expect(hasAgentTag("triage;agentic-qa;p1")).toBe(true);
    expect(hasAgentTag("agentic-qa-run-3")).toBe(false);
    expect(hasAgentTag("not-agentic-qa")).toBe(false);
    expect(hasAgentTag(undefined)).toBe(false);
    expect(hasAgentTag(["agentic-qa"])).toBe(false);
  });
});
